/**
 * Single source of truth → derived artefacts.
 *
 * Source:  packrivo-v2/app/globals.css   (@theme tokens)
 *          packrivo-v2/lib/pricing.ts    (STYLE_BASE / MATERIALS / PRINTS / FINISHES / TIER_FACTOR)
 * Output:  packrivo-shared/tokens.css
 *          packrivo-shared/pricing.json
 *          packrivo-home-v4/assets/tokens.css      (copy)
 *          packrivo-quote/includes/pricing.json    (copy)
 *
 * Run: node packrivo-shared/build-shared.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const V2 = `${ROOT}/packrivo-v2`;
const SHARED = `${ROOT}/packrivo-shared`;

mkdirSync(SHARED, { recursive: true });

const KEY = '(?:"([a-z-]+)"|([a-z-]+))';
const STR = '(?:"([^"]*)"|\'([^\']*)\')';

/* ---------- tokens ---------- */

const css = readFileSync(`${V2}/app/globals.css`, 'utf8');
const themeBlock = css.match(/@theme\s*\{([\s\S]*?)\n\}/);
if (!themeBlock) throw new Error('@theme block not found in globals.css');

const tokens = [];
for (const line of themeBlock[1].split('\n')) {
  const m = line.match(/^\s*(--[a-z0-9-]+)\s*:\s*(.+?);\s*$/i);
  if (m) tokens.push([m[1], m[2]]);
}

const tokenCss = [
  '/* Generated by packrivo-shared/build-shared.mjs — do not edit by hand. */',
  '/* Source: packrivo-v2/app/globals.css @theme */',
  ':root {',
  ...tokens.map(([k, v]) => `  --pk${k.replace(/^--/, '-')}: ${v};`),
  '}',
  '',
].join('\n');

writeFileSync(`${SHARED}/tokens.css`, tokenCss, 'utf8');

/* ---------- pricing ---------- */

const ts = readFileSync(`${V2}/lib/pricing.ts`, 'utf8');

function objectBlock(name) {
  const start = ts.indexOf(`export const ${name}`);
  if (start < 0) throw new Error(`${name} not found`);
  const open = ts.indexOf('{', start);
  const close = ts.indexOf('\n}', open);
  return ts.slice(open + 1, close);
}

const pick = (m, i) => (m[i] !== undefined ? m[i] : m[i + 1]);

const styles = {};
for (const line of objectBlock('STYLE_BASE').split('\n')) {
  const m = line.match(new RegExp(`^\\s*${KEY}\\s*:\\s*\\{\\s*label:\\s*${STR},\\s*base:\\s*([\\d.]+)`));
  if (m) styles[pick(m, 1)] = { label: pick(m, 3), base: Number(m[5]) };
}

const materials = {};
for (const line of objectBlock('MATERIALS').split('\n')) {
  const m = line.match(new RegExp(`^\\s*${KEY}\\s*:\\s*\\{\\s*label:\\s*${STR},\\s*factor:\\s*([\\d.]+),\\s*note:\\s*${STR}`));
  if (m) materials[pick(m, 1)] = { label: pick(m, 3), factor: Number(m[5]), note: pick(m, 6) };
}

function simpleMap(name, field) {
  const out = {};
  for (const line of objectBlock(name).split('\n')) {
    const m = line.match(new RegExp(`^\\s*${KEY}\\s*:\\s*\\{\\s*label:\\s*${STR},\\s*${field}:\\s*([\\d.]+)`));
    if (m) out[pick(m, 1)] = { label: pick(m, 3), [field]: Number(m[5]) };
  }
  return out;
}

const prints = simpleMap('PRINTS', 'add');
const finishes = simpleMap('FINISHES', 'add');

const tierStart = ts.indexOf('const TIER_FACTOR');
const tierBlock = ts.slice(tierStart, ts.indexOf('];', tierStart));
const tiers = [...tierBlock.matchAll(/\[\s*(\d+)\s*,\s*([\d.]+)\s*\]/g)].map((m) => [Number(m[1]), Number(m[2])]);
const sourceNumber = (name) => {
  const match = ts.match(new RegExp(`export const ${name}\\s*=\\s*([\\d.]+)`));
  if (!match) throw new Error(`${name} not found`);
  return Number(match[1]);
};

const spec = {
  generatedFrom: ['app/globals.css', 'lib/pricing.ts'],
  styles,
  materials,
  prints,
  finishes,
  tiers,
  setup: { print: 220, die: 120 },
  sizeRef: [30, 20, 10],
  rules: { freePrintSetupFrom: 2500, freeDieFrom: 5000, rushPercent: 22, tierFloor: 0.64, fee_percent: sourceNumber('FEE_PERCENT'), min_fee: sourceNumber('MIN_FEE') },
};

const json = JSON.stringify(spec, null, 2) + '\n';
writeFileSync(`${SHARED}/pricing.json`, json, 'utf8');

copyFileSync(`${SHARED}/tokens.css`, `${ROOT}/packrivo-wp/packrivo-home-v4/assets/tokens.css`);
copyFileSync(`${SHARED}/pricing.json`, `${ROOT}/packrivo-wp/packrivo-quote/includes/pricing.json`);

const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);
console.log('tokens:', tokens.length, 'vars →', hash(tokenCss));
console.log(
  'styles:', Object.keys(styles).length,
  '| materials:', Object.keys(materials).length,
  '| prints:', Object.keys(prints).length,
  '| finishes:', Object.keys(finishes).length,
);
console.log('tiers:', tiers.map((t) => t[0]).join(','));
console.log('pricing.json →', hash(json), `${Math.round(json.length / 1024)} KB`);
console.log('copied to child theme + plugin');
